#include <stdio.h>

int қосынды(int сан) {
    int қос = 0;

    if (сан < 0) {
        сан = -сан;
    }
    while (сан > 0) {
        қос += сан % 10;
        сан /= 10;
    }
    return қос;
}

int main(void) {
    int сан, бір = 0, екі = 0, бір_қос = 0, екі_қос = 0;
    double орта1, орта2;

    while (scanf("%d", &сан) == 1 && сан != 0) {
        if (сан % қосынды(сан) == 0) {
            бір++;
            бір_қос += сан;
        } else {
            екі++;
            екі_қос += сан;
        }
    }
    if (бір > 0) {
        орта1 = (double)бір_қос / бір;
    } else {
        орта1 = 0.0;
    }
    if (екі > 0) {
        орта2 = (double)екі_қос / екі;
    } else {
        орта2 = 0.0;
    }
    printf("ТОП1_САНЫ: %d\n", бір);
    printf("ТОП1_ОРТА: %.2f\n", орта1);
    printf("ТОП2_САНЫ: %d\n", екі);
    printf("ТОП2_ОРТА: %.2f\n", орта2);

    return 0;
}
